#!/usr/bin/env node
// Prints SQL that fills public.national_holiday from the Cabinet Office's
// official holiday CSV (内閣府「国民の祝日」について).
//
//   node supabase/scripts/national-holidays.mjs [year ...] [--file syukujitsu.csv]
//
// Without years: the current and the next year (Asia/Tokyo). Without --file
// the CSV is downloaded from CSV_URL. The output replaces the given years (delete + insert, safe to rerun); put
// it into a new migration (npx supabase migration new national_holidays_<year>)
// so the hosted project gets it too.
//
// CSV format (checked 2026-11-26): Shift_JIS, header
// "国民の祝日・休日月日,国民の祝日・休日名称", rows like "2027/3/22,休日".
// The Cabinet Office publishes the next year's holidays each February.
// English and German names come from NAMES below; an unknown name stops the
// script, so a new holiday gets its translations before it is stored.

import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export const CSV_URL = 'https://www8.cao.go.jp/chosei/shukujitsu/syukujitsu.csv';

export const NAMES = {
  '元日': { en: "New Year's Day", de: 'Neujahr' },
  '成人の日': { en: 'Coming of Age Day', de: 'Tag der Volljährigkeit' },
  '建国記念の日': { en: 'National Foundation Day', de: 'Staatsgründungstag' },
  '天皇誕生日': { en: "Emperor's Birthday", de: 'Geburtstag des Kaisers' },
  '春分の日': { en: 'Vernal Equinox Day', de: 'Frühlingsanfang' },
  '昭和の日': { en: 'Shōwa Day', de: 'Shōwa-Tag' },
  '憲法記念日': { en: 'Constitution Memorial Day', de: 'Verfassungstag' },
  'みどりの日': { en: 'Greenery Day', de: 'Tag des Grüns' },
  'こどもの日': { en: "Children's Day", de: 'Kindertag' },
  '海の日': { en: 'Marine Day', de: 'Tag des Meeres' },
  '山の日': { en: 'Mountain Day', de: 'Tag der Berge' },
  '敬老の日': { en: 'Respect for the Aged Day', de: 'Tag der Achtung vor dem Alter' },
  '秋分の日': { en: 'Autumnal Equinox Day', de: 'Herbstanfang' },
  'スポーツの日': { en: 'Sports Day', de: 'Tag des Sports' },
  '文化の日': { en: 'Culture Day', de: 'Tag der Kultur' },
  '勤労感謝の日': { en: 'Labour Thanksgiving Day', de: 'Tag des Dankes für die Arbeit' },
  // Substitute holiday (振替休日) and bridge day (国民の休日) are both "休日".
  '休日': { en: 'Substitute or bridge holiday', de: 'Ersatz- oder Brückenfeiertag' },
};

export function parseCsv(text, years) {
  const lines = text.replace(/^﻿/, '').split(/\r?\n/).filter((l) => l.trim() !== '');
  if (!lines[0]?.startsWith('国民の祝日・休日月日,')) {
    throw new Error(`unexpected CSV header: ${lines[0]}`);
  }
  const rows = [];
  for (const line of lines.slice(1)) {
    const m = /^(\d{4})\/(\d{1,2})\/(\d{1,2}),(.+)$/.exec(line.trim());
    if (!m) throw new Error(`unexpected CSV row: ${line}`);
    const [, y, mo, d, ja] = m;
    if (!years.includes(Number(y))) continue;
    const names = NAMES[ja];
    if (!names) throw new Error(`no translation for "${ja}" (${line}); add it to NAMES`);
    rows.push({ date: `${y}-${mo.padStart(2, '0')}-${d.padStart(2, '0')}`, name: { ja, ...names } });
  }
  for (const y of years) {
    if (!rows.some((r) => r.date.startsWith(`${y}-`))) {
      throw new Error(`the CSV has no holidays for ${y} (published each February)`);
    }
  }
  return rows;
}

const quote = (s) => `'${s.replaceAll("'", "''")}'`;

export function toSql(rows, years) {
  const values = rows.map((r) => `  (${quote(r.date)}, ${quote(JSON.stringify(r.name))})`).join(',\n');
  return `-- Japanese national holidays ${years.join(', ')} from the Cabinet Office CSV
-- (${CSV_URL}), generated by supabase/scripts/national-holidays.mjs.
-- Replaces the listed years, so a holiday the Cabinet Office moved or
-- removed does not linger.

delete from public.national_holiday
 where extract(year from date)::integer in (${years.join(', ')});

insert into public.national_holiday (date, name) values
${values};
`;
}

async function main(argv) {
  const fileIdx = argv.indexOf('--file');
  const file = fileIdx >= 0 ? argv[fileIdx + 1] : null;
  const rest = argv.filter((_, i) => fileIdx < 0 || (i !== fileIdx && i !== fileIdx + 1));
  const bad = rest.filter((a) => !/^\d{4}$/.test(a));
  if (bad.length > 0) throw new Error(`unknown arguments: ${bad.join(' ')}`);
  let years = rest.map(Number);
  if (years.length === 0) {
    const thisYear = Number(new Intl.DateTimeFormat('en', { timeZone: 'Asia/Tokyo', year: 'numeric' }).format(new Date()));
    years = [thisYear, thisYear + 1];
  }
  const bytes = file ? await readFile(file) : await download();
  const text = new TextDecoder('shift_jis').decode(bytes);
  process.stdout.write(toSql(parseCsv(text, years), years));
}

async function download() {
  const res = await fetch(CSV_URL);
  if (!res.ok) throw new Error(`${CSV_URL}: HTTP ${res.status}`);
  return new Uint8Array(await res.arrayBuffer());
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
